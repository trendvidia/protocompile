// genaliases writes a Go file that re-exports every exported identifier of
// another package: a type alias for each type, and a copy of each constant
// and variable.
//
// gen/pxf and gen/protowire/schema/v1 used to hold generated code for
// pxf/bignum.proto and protowire/schema/v1/{descriptor,report}.proto. That
// code now lives in github.com/trendvidia/protos, and a program that linked
// both registered each file twice and panicked at startup. The gen packages
// are now aliases onto protos, so existing importers keep building and
// nothing registers twice (trendvidia/protos#1).
//
// Usage, from a go:generate line in the package to write:
//
//	go run ../../internal/cmd/genaliases -from github.com/trendvidia/protos/pxf -pkg pxf -o aliases.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	from := flag.String("from", "", "import path of the package to alias")
	pkg := flag.String("pkg", "", "package name of the output file")
	out := flag.String("o", "", "output file")
	flag.Parse()
	if *from == "" || *pkg == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "genaliases: -from, -pkg and -o are required")
		os.Exit(2)
	}
	if err := run(*from, *pkg, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genaliases:", err)
		os.Exit(1)
	}
}

func run(from, pkg, out string) error {
	dir, err := exec.Command("go", "list", "-f", "{{.Dir}}", from).Output()
	if err != nil {
		return fmt.Errorf("locating %s: %w", from, err)
	}
	files, err := filepath.Glob(filepath.Join(strings.TrimSpace(string(dir)), "*.go"))
	if err != nil {
		return err
	}

	var types, consts, vars []string
	fset := token.NewFileSet()
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, f, nil, parser.SkipObjectResolution)
		if err != nil {
			return err
		}
		for _, decl := range file.Decls {
			switch decl := decl.(type) {
			case *ast.FuncDecl:
				if decl.Recv == nil && decl.Name.IsExported() {
					// Generated protobuf code declares no exported functions;
					// one appearing means this tool needs to learn to wrap it.
					return fmt.Errorf("%s: exported function %s has no alias form", f, decl.Name)
				}
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						if spec.Name.IsExported() {
							types = append(types, spec.Name.Name)
						}
					case *ast.ValueSpec:
						for _, name := range spec.Names {
							if !name.IsExported() {
								continue
							}
							if decl.Tok == token.CONST {
								consts = append(consts, name.Name)
							} else {
								vars = append(vars, name.Name)
							}
						}
					}
				}
			}
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n// Code generated by internal/cmd/genaliases. DO NOT EDIT.\n\n", header)
	fmt.Fprintf(&b, "package %s\n\nimport protos %q\n", pkg, from)
	block := func(kw string, names []string, form string) {
		if len(names) == 0 {
			return
		}
		sort.Strings(names)
		fmt.Fprintf(&b, "\n%s (\n", kw)
		for _, n := range names {
			fmt.Fprintf(&b, form, n, n)
		}
		b.WriteString(")\n")
	}
	block("type", types, "\t%s = protos.%s\n")
	block("const", consts, "\t%s = protos.%s\n")
	block("var", vars, "\t%s = protos.%s\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0666) //nolint:gosec
}

